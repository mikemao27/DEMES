"""
Ties every other module into one coherent turn of conversation: this is where the pieces built and tested standalone across the rest of 
the codebase actually get wired together and run for real.

WHAT PROBLEM THIS FILE SOLVES: Every layer built so far (the lexicon, the grammar, compositional semantics, figurative repair, the
world model, discourse tracking) works correctly on its own: each has its own tests proving that. But a working system isn't just a pile of correct, 
independent pieces; it's those pieces actually calling each other in the right order, on real data, with each one's output feeding the next one's
input. That's this file's entire job, and only this file's job: no new linguistic mechanism gets invented here, only orchestration of mechanisms that 
already exist.

WHAT ONE TURN ACTUALLY DOES, IN ORDER:
    1. Advance the world model's turn clock (so this turn's events get the right relative timing).

    2. Parse the utterance, keeping both the LogicalForm and the derivation tree. If it fails to parse at all, try resolving it as a bare fragment answer
    (QUDStack.resolve_fragment) against whatever question is currently under discussion, before giving up as a genuine parse failure.

    3. Register any newly-mentioned nouns as discourse referents, using the ORIGINAL (pre-resolution) arguments: a pronoun is never itself a new lexicon noun,
    so this step naturally never registers a pronoun as if it were a fresh entity.

    4. Resolve every pronoun argument: try cataphora first (forward reference within this sentence, licensed only by Principle C), then fall back to ordinary backward 
    resolution against the world model's active referents, honoring whatever gender/number/animacy the specific pronoun carries.

    5. Check every presupposition trigger word in the utterance against what's already known, accommodating (assuming, and recording) anything genuinely new rather than 
    failing on it.

    6. Disambiguate any polysemous word against its sentence-mates' selectional constraints.

    7. Classify the utterance's speech act, and detect focus (what a focus particle like "only"/"even" actually combined with in the derivation tree) if one is present.

    8. Compile and evaluate truth via SemanticCompiler; if the predicate was idiom-tagged during parsing, look up and attach its real (figurative.py) meaning to the payload; if the
    predicate declares a selectional requirement for an argument position that the actual argument doesn't literally satisfy, attempt metonymic/metaphorical repair and attach it
    if one applies; if the sentence is the copula-identity-relation shape ("Bob is an employee"), write it into the Episodic Fact Graph as an IS_A fact; if the sentence is an
    ordinary (non-quantified, non-negated, two-argument) claim that evaluated true, record it as a binary relational fact in the world model, so a later multi-quantifier sentence
    has something real to check its relation against.

    9. Record the utterance as an event on the world model's episodic timeline.

    10. Collect any scalar implicatures generated by the words actually used.

    11. If the predicate is a clausal-complement mental-predicate verb (its logical form carries a nested embedded LogicalForm as one of its arguments: core/parser.py's clausal-complement extraction),
    open a Modal & Attitude context for the matrix subject and assert the embedded clause into that context only, never into global reality: this is what keeps "John thinks Mary is home" from corrupting what
    DEMES knows to actually be true.

    12. If a wh-word ("who"/"what") is among the arguments (a non-movement wh-question core/parser.py could actually produce, e.g. "Who walked?" or "What is the suitcase?") push a QUDEntry marking that argument
    position as the open slot onto this pipeline's persistent QUDStack, so a later bare-fragment answer has something real to fill in.

    13. If the utterance began with a recognized discourse connective ("However, Mary stayed.": stripped before parsing, step 2, since it isn't part of the clause's own content), or a real Aktionsart was
    derived this turn or the previous one (currently only possible via an idiom-tagged predicate's own Explication: ordinary verbs still have nothing real to derive one from until the lexicon migration),
    and this isn't the conversation's very first turn, classify how this turn relates to the previous one (SDRT's closed six-relation core) from whichever of those two signals is actually available.

A COORDINATED sentence ("John left and Mary left") runs every step above uniformly over a list of conjuncts (one conjunct for an ordinary sentence, two for a coordinated one) rather than as a special case bolted 
on afterward: each conjunct gets its own noun registration, pronoun resolution, and truth evaluation, and the coordinator's own connective (AND/OR, from core/parser.py's get_coordinator_connective) combines their 
individual truth values into the turn's overall one.

WHAT THIS FILE DOES NOT DO: It doesn't invoke a language model anywhere: that's interface/neural_bridge.py, not built yet, and nothing here reaches for it as a silent fallback. 
It also doesn't paper over gaps in what the grammar can parse: cataphora resolution, presupposition triggers, and several other mechanisms wired in here will only ever fire on 
the sentence shapes core/parser.py can actually produce today: see the architecture plan's "known partial implementations" section for the current honest list of what that does 
and doesn't cover.
"""

